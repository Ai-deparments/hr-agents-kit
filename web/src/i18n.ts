export const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

type T = ((key: string) => string) & { l: (uz: string, ru: string, en?: string) => string };

/** t(key) from the dictionary; t.l(uz, ru, en?) for one-off texts — only the chosen language is shown. */
export function useT(): T {
  const { lang } = useContext(LangCtx);
  const t = ((key: string) => dict[key]?.[lang] ?? dict[key]?.en ?? key) as T;
  t.l = (uz, ru, en) => (lang === "uz" ? uz : lang === "en" ? en ?? ru : ru);
  return t;
}

/** Translate an enum code (e.g. a status from the server) via `prefix + code`; unknown codes are shown as is. */
export function tEnum(t: (key: string) => string, prefix: string, code: string) {
  const k = prefix + code;
  const r = t(k);
  return r === k ? code : r;
}
